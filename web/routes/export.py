"""Report export routes — Markdown and PDF downloads."""

from __future__ import annotations

import json
import tempfile
from datetime import datetime
from pathlib import Path
from flask import Blueprint, jsonify, make_response
from web.security import current_org_id, permission_required

ROOT = Path(__file__).resolve().parents[2]

export_bp = Blueprint("export", __name__, url_prefix="/api/cases")


def _get_db():
    import sqlite3
    db_path = ROOT / "data" / "soc_operator.db"
    db_path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(db_path))
    conn.row_factory = sqlite3.Row
    return conn


def _generate_markdown(case, activity, chat_history) -> str:
    """Generate a Markdown report for a case."""
    now = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        f"# SOC Investigation Report",
        "",
        f"**Generated:** {now}",
        f"**Case:** {case['title']}",
        f"**Severity:** {case['severity']}",
        f"**Status:** {case['status']}",
        "",
        "---",
        "",
        "## Executive Summary",
        "",
        case["summary"] or "No summary available.",
        "",
    ]

    # Activity timeline
    if activity:
        lines.extend([
            "## Investigation Timeline",
            "",
            "| Step | Status | Detail |",
            "|---|---|---|",
        ])
        for entry in activity:
            lines.append(f"| {entry['step']} | {entry['status']} | {entry['detail'] or ''} |")
        lines.append("")

    # Chat analyst notes
    analyst_notes = [m for m in chat_history if m["sender_type"] == "assistant"]
    if analyst_notes:
        lines.extend([
            "## Analyst Notes",
            "",
        ])
        for note in analyst_notes:
            lines.append(f"### {note['created_at']}")
            lines.append(note["content"])
            lines.append("")

    # Tool executions
    conn = _get_db()
    executions = conn.execute(
        "SELECT * FROM tool_executions WHERE action_id IN (SELECT id FROM chat_actions WHERE case_id = ?) ORDER BY created_at",
        (case["id"],),
    ).fetchall()
    conn.close()

    if executions:
        lines.extend([
            "## Tool Executions",
            "",
            "| Command | Status | Exit Code |",
            "|---|---|---|",
        ])
        for ex in executions:
            lines.append(f"| `{ex['command_preview']}` | {ex['status']} | {ex['exit_code'] or 'N/A'} |")
        lines.append("")

    # Recommendations
    lines.extend([
        "## Recommendations",
        "",
        "1. Review all IOCs in the enrichment data",
        "2. Verify containment actions were effective",
        "3. Update the incident timeline with new findings",
        "4. Close the case when investigation is complete",
        "",
        "---",
        f"*Report generated by AI SOC Operator*",
    ])

    return "\n".join(lines)


def _markdown_to_pdf(md_content: str) -> bytes:
    """Convert Markdown to PDF using WeasyPrint."""
    import markdown
    html_body = markdown.markdown(md_content, extensions=["tables", "fenced_code"])

    html = f"""<!DOCTYPE html>
<html>
<head>
    <meta charset="utf-8">
    <style>
        body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; margin: 40px; color: #1a1a1a; line-height: 1.6; }}
        h1 {{ color: #1e40af; border-bottom: 2px solid #1e40af; padding-bottom: 8px; }}
        h2 {{ color: #1e3a5f; margin-top: 24px; }}
        h3 {{ color: #374151; }}
        table {{ border-collapse: collapse; width: 100%; margin: 16px 0; }}
        th, td {{ border: 1px solid #d1d5db; padding: 8px 12px; text-align: left; }}
        th {{ background: #f3f4f6; font-weight: 600; }}
        code {{ background: #f3f4f6; padding: 2px 6px; border-radius: 4px; font-size: 0.9em; }}
        hr {{ border: none; border-top: 1px solid #e5e7eb; margin: 24px 0; }}
        strong {{ color: #111827; }}
    </style>
</head>
<body>{html_body}</body>
</html>"""

    try:
        from weasyprint import HTML
        pdf = HTML(string=html).write_pdf()
        return pdf
    except ImportError:
        # Fallback: return HTML as bytes
        return html.encode("utf-8")


@export_bp.get("/<int:case_id>/export/md")
@permission_required("report.export")
def export_markdown(case_id: int):
    conn = _get_db()
    org_id = current_org_id(conn)
    case = conn.execute("SELECT * FROM cases WHERE id = ? AND org_id = ?", (case_id, org_id)).fetchone()
    if not case:
        conn.close()
        return jsonify({"error": "not found"}), 404

    activity = conn.execute(
        "SELECT * FROM activity_log WHERE run_id IN (SELECT run_id FROM cases WHERE id = ?) ORDER BY timestamp",
        (case_id,),
    ).fetchall()

    # Get chat history
    chat_history = []
    thread = conn.execute(
        "SELECT * FROM chat_threads WHERE case_id = ? ORDER BY updated_at DESC LIMIT 1",
        (case_id,),
    ).fetchone()
    if thread:
        chat_history = [dict(r) for r in conn.execute(
            "SELECT * FROM chat_messages WHERE thread_id = ? ORDER BY created_at",
            (thread["id"],),
        ).fetchall()]
    conn.close()

    md = _generate_markdown(case, activity, chat_history)

    response = make_response(md)
    response.headers["Content-Type"] = "text/markdown; charset=utf-8"
    response.headers["Content-Disposition"] = f'attachment; filename="report-{case_id}.md"'
    return response


@export_bp.get("/<int:case_id>/export/pdf")
@permission_required("report.export")
def export_pdf(case_id: int):
    conn = _get_db()
    org_id = current_org_id(conn)
    case = conn.execute("SELECT * FROM cases WHERE id = ? AND org_id = ?", (case_id, org_id)).fetchone()
    if not case:
        conn.close()
        return jsonify({"error": "not found"}), 404

    activity = conn.execute(
        "SELECT * FROM activity_log WHERE run_id IN (SELECT run_id FROM cases WHERE id = ?) ORDER BY timestamp",
        (case_id,),
    ).fetchall()

    chat_history = []
    thread = conn.execute(
        "SELECT * FROM chat_threads WHERE case_id = ? ORDER BY updated_at DESC LIMIT 1",
        (case_id,),
    ).fetchone()
    if thread:
        chat_history = [dict(r) for r in conn.execute(
            "SELECT * FROM chat_messages WHERE thread_id = ? ORDER BY created_at",
            (thread["id"],),
        ).fetchall()]
    conn.close()

    md = _generate_markdown(case, activity, chat_history)
    pdf_bytes = _markdown_to_pdf(md)

    # Check if WeasyPrint is available
    try:
        from weasyprint import HTML
        content_type = "application/pdf"
        ext = "pdf"
    except ImportError:
        content_type = "text/html; charset=utf-8"
        ext = "html"

    response = make_response(pdf_bytes)
    response.headers["Content-Type"] = content_type
    response.headers["Content-Disposition"] = f'attachment; filename="report-{case_id}.{ext}"'
    return response


@export_bp.get("/<int:case_id>/export/stix")
@permission_required("report.export")
def export_stix(case_id: int):
    conn = _get_db()
    org_id = current_org_id(conn)
    case = conn.execute("SELECT * FROM cases WHERE id = ? AND org_id = ?", (case_id, org_id)).fetchone()
    if not case:
        conn.close()
        return jsonify({"error": "not found"}), 404
    observables = conn.execute(
        "SELECT * FROM observables WHERE case_id = ? AND org_id = ? ORDER BY created_at",
        (case_id, org_id),
    ).fetchall()
    conn.close()
    from web.services.intel_export import stix_json_for_case

    response = make_response(stix_json_for_case(dict(case), [dict(row) for row in observables]))
    response.headers["Content-Type"] = "application/stix+json; charset=utf-8"
    response.headers["Content-Disposition"] = f'attachment; filename="case-{case_id}.stix.json"'
    return response
